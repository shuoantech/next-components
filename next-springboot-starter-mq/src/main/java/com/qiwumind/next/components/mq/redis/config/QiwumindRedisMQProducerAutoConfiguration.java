package com.qiwumind.next.components.mq.redis.config;

import com.qiwumind.next.components.mq.redis.core.RedisMQTemplate;
import com.qiwumind.next.components.mq.redis.core.interceptor.RedisMessageInterceptor;
import com.qiwumind.next.components.redis.config.QiwumindRedisAutoConfiguration;
import lombok.extern.slf4j.Slf4j;
import org.springframework.boot.autoconfigure.AutoConfiguration;
import org.springframework.context.annotation.Bean;
import org.springframework.data.redis.core.StringRedisTemplate;

import java.util.List;

/**
 * Redis 消息队列 Producer 配置类
 * @author qiwumind
 */
@Slf4j
@AutoConfiguration(after = QiwumindRedisAutoConfiguration.class)
public class QiwumindRedisMQProducerAutoConfiguration {

    @Bean
    public RedisMQTemplate redisMQTemplate(StringRedisTemplate redisTemplate,
                                           List<RedisMessageInterceptor> interceptors) {
        RedisMQTemplate redisMQTemplate = new RedisMQTemplate(redisTemplate);
        // 添加拦截器
        interceptors.forEach(redisMQTemplate::addInterceptor);
        return redisMQTemplate;
    }

}
